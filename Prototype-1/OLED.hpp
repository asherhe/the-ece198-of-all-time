// testing observations:
// the OLED can use 3.3V or 5V
// the pixels are monochrome
// after making the pixel art in Krita, I used https://jlamch.net/MXChipWelcome/
// for the bitmaps fitting more information means reduced readability this code
// is suboptimal since the entire display is updated every single time; not just
// the parts that change

#pragma once

#include <Adafruit_SSD1306.h>
#include <Wire.h>

// screen variables
const int SCREEN_WIDTH = 128, SCREEN_HEIGHT = 64, OLED_RESET = -1;

class OLED {
private:
  // display object
  Adafruit_SSD1306 display;

  unsigned long previousTimeUpdate = 0;
  unsigned long previousHeartUpdate = 0;

  bool bigHeart = false;

  unsigned int heart_rate =
      150; // replace this with the oximeter heart rate
  unsigned long workout_time =
      30 * 60 * 1000; // 30 minutes; the physician should be able to set this

  void draw_frame(bool big_or_small);
  void update_bpm();
  void draw_heart(bool big_or_small);
  void time_left();

public:
  OLED() : display(SCREEN_WIDTH, SCREEN_HEIGHT, &Wire, OLED_RESET) {}

  void setup();
  void loop();
};

