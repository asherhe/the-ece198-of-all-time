void draw_heart(bool big_or_small) {
  unsigned char const * heart = big_heart;

  if (big_or_small == false){
  heart = small_heart;
  }

  display.drawBitmap(
  0, (SCREEN_HEIGHT - HEART_HEIGHT),
  heart, HEART_WIDTH, HEART_HEIGHT, 1);
}

void update_bpm(){
  if (safe_heart == false){
	display.setCursor(15, 23);
	display.print("!!!");
  }
  else {
	if (heart_rate >= 100){
	display.setCursor(15, 23);
 	} else { // 2-digit heart rate
	display.setCursor(21, 23);
  	}

	display.setTextSize(2);
    display.print(heart_rate);
  }
}

// initialize so don't have to calculate continuously
unsigned long hours{workout_time/(60UL*60*1000)};
unsigned long minutes{(workout_time % (60UL*60*1000)) / (60*1000UL)};
unsigned long seconds{(workout_time % (60UL*1000)) / 1000UL}; // not total seconds

void update_timer(){
	if (seconds > 0){
		--seconds;
	} else {
		if (minutes > 0){
			--minutes;
			seconds = 59;
		} else if (hours > 0){
			--hours;
			minutes = 59;
			seconds = 59;
		}
	}
}

void draw_timer(){
	display.setTextSize(2);

	// kind of repetitive
	display.setCursor(67, 0);
	if (hours < 10)
		display.print("0");
	display.print(hours);
	display.print(":");

	if (minutes < 10)
		display.print("0");
	display.print(minutes);
	display.print(":");

	display.setCursor(103, 16);
	if (seconds < 10)
	display.print("0");
	display.print(seconds);
}

void update_reps(){
	display.setCursor(67, 32);
	display.print("Reps: ");
	display.setCursor(103, 48);
	display.print(reps);
}