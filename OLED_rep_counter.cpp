void setup() {
  // I2C
  display.begin(SSD1306_SWITCHCAPVCC, 0x3C);
  display.clearDisplay();
  display.setTextColor(SSD1306_WHITE);
}

// copied the following from ChatGPT
unsigned long previousTimeUpdate = 0;
unsigned long previousHeartUpdate = 0;

bool bigHeart = false;
bool firstFrame = true;

bool previousBigHeart = false;
bool previousSafeHeart = true;
unsigned int previousHeartRate = 0;
unsigned int previousReps = 0;

void loop() {
    unsigned long current_millis = millis();

    // Update clock every second
    if (current_millis - previousTimeUpdate >= 1000) {
        previousTimeUpdate = current_millis;
		update_timer();
        draw_frame(bigHeart, true);
    }

    // Animate heart independently and according to heart_rate
    unsigned long heartInterval;
	if (bigHeart) {
		heartInterval = (1600UL * 25UL) / heart_rate;
	} else {
		heartInterval = (800UL * 25UL) / heart_rate;
	}

    if (current_millis - previousHeartUpdate >= heartInterval) {
        previousHeartUpdate = current_millis;
        bigHeart = !bigHeart;

        draw_frame(bigHeart, false);
    }
}


void draw_frame(bool big_or_small, bool updateClock) {

    bool changed = false;

    // Update heart and BPM if either has changed
    if (firstFrame ||
        big_or_small != previousBigHeart ||
        safe_heart != previousSafeHeart ||
        (safe_heart && heart_rate != previousHeartRate)) {

        display.fillRect(0, 0, 64, 64, SSD1306_BLACK);

        update_bpm();
        draw_heart(big_or_small);

        previousBigHeart = big_or_small;
        previousSafeHeart = safe_heart;
        previousHeartRate = heart_rate;

        changed = true;
    }

    // Update timer once per second
    if (firstFrame || updateClock) {
        display.fillRect(64, 0, 64, 32, SSD1306_BLACK);
        draw_timer();
        changed = true;
    }

    // Update reps only if they have changed
    if (firstFrame || reps != previousReps) {
		// the 'Reps:' will not be drawn over since it is constant
        display.fillRect(103, 48, 25, 16, SSD1306_BLACK);
        update_reps();

        previousReps = reps;
        changed = true;
    }

    if (changed) {
        display.display();
    }

    firstFrame = false;
}

